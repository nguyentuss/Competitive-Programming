#include <bits/stdc++.h>

using namespace std;

int n;
int C[107][107];


void init() {
	for (int i = 0 ; i <= 100 ; i++) {
		C[i][i] = 1;
		C[i][0] = 1;
	}
	for (int i = 1 ; i <= 100 ; i++) {
		for (int j = 0 ; j < i ; j++) {
			C[i][j] = C[i - 1][j] + C[i - 1][j - 1];
		}
	}
	cout << C[n][4];
}

int main() {
	ios_base::sync_with_stdio(0); cin.tie(NULL);
	freopen("dagiac.inp","r",stdin);
	freopen("dagiac.out","w",stdout);
	cin >> n;
	init();
	return 0;
}